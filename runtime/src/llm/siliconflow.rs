use async_openai::{
    Client,
    config::OpenAIConfig,
    types::chat::{
        ChatChoiceLogprobs, ChatCompletionRequestMessage, CreateChatCompletionRequest,
        CreateChatCompletionRequestArgs, FinishReason, ReasoningEffort,
    },
};
use async_trait::async_trait;
use futures::StreamExt;
use kernel::{
    client::{ChatClient, ChunkStream},
    message::{Information, Role},
    model::{ModelFamily, ModelModal},
};
use serde::{Deserialize, Serialize};

use crate::kit::message_kit;

#[derive(Debug, Deserialize, Serialize, Clone)]
pub struct ChatStreamResponse {
    /// A unique identifier for the chat completion. Each chunk has the same ID.
    pub id: String,
    pub choices: Vec<ChatChoiceStream>,
    /// The Unix timestamp (in seconds) of when the chat completion was created. Each chunk has the same timestamp.
    pub created: u32,
    /// The model to generate the completion.
    pub model: String,

    pub system_fingerprint: Option<String>,
    /// The object type, which is always `chat.completion.chunk`.
    pub object: String,
}

#[derive(Debug, Deserialize, Serialize, Clone, PartialEq)]
pub struct ChatChoiceStream {
    /// The index of the choice in the list of choices.
    pub index: u32,
    pub delta: StreamResponseDelta,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub finish_reason: Option<FinishReason>,
    /// Log probability information for the choice.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub logprobs: Option<ChatChoiceLogprobs>,
}

#[derive(Debug, Deserialize, Serialize, Clone, PartialEq)]
pub struct StreamResponseDelta {
    /// The contents of the chunk message.
    pub content: Option<String>,
    /// The role of the author of this message.
    pub role: Option<Role>,
    /// The refusal message generated by the model.
    pub reasoning_content: Option<String>,
}

pub struct SiliconflowClient {
    pub model: String,
    pub client: Client<OpenAIConfig>,
    pub modals: Vec<ModelModal>,
}
#[async_trait]
impl ChatClient for SiliconflowClient {
    fn model_info(&self) -> (ModelFamily, String, Vec<ModelModal>) {
        (
            ModelFamily::DeepSeek,
            self.model.to_string(),
            self.modals.clone(),
        )
    }
    async fn stream(
        &self,
        messages: Vec<kernel::message::RoleMessage>,
    ) -> anyhow::Result<ChunkStream> {
        let messages: Vec<ChatCompletionRequestMessage> = messages
            .into_iter()
            .map(|v| message_kit::to_sdk_message(v))
            .collect();
        let request: CreateChatCompletionRequest = CreateChatCompletionRequestArgs::default()
            .model(self.model.clone())
            .reasoning_effort(ReasoningEffort::Medium)
            .messages(messages)
            .stream(true)
            .build()?;
        let stream = self
            .client
            .chat()
            .create_stream_byot::<CreateChatCompletionRequest, ChatStreamResponse>(request)
            .await?;
        let mut in_think = false;
        let stream = stream.map(move |r| {
            let r = r
                .map(|mut v| {
                    if v.choices.is_empty() {
                        return "".to_string();
                    }
                    let text = v.choices[0].delta.content.take();
                    let reasoning = v.choices[0].delta.reasoning_content.take();
                    if let Some(reasoning) = reasoning {
                        if !in_think {
                            in_think = true;
                            return format!("<think>\n{}", reasoning);
                        } else {
                            return reasoning;
                        }
                    }
                    if let Some(text) = text {
                        if in_think {
                            in_think = false;
                            return format!("\n</think>\n{}", text);
                        } else {
                            return text;
                        }
                    }
                    return "".to_string();
                    // println!("{}", v);
                    // "".to_string()
                })
                .map(|v| Ok(v))
                .flatten()
                .map_err(|e| anyhow::anyhow!(e));
            r
        });
        return Ok(stream.boxed());
    }
}
