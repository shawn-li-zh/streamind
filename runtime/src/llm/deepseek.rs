use async_openai::{
    Client,
    config::OpenAIConfig,
    types::chat::{ChatChoiceLogprobs, FinishReason, ReasoningEffort},
};
use async_trait::async_trait;
use futures::StreamExt;
use kernel::{
    client::{ChatClient, ChunkStream},
    message::{Information, Role},
    model::ModelFamily,
};
use serde::{Deserialize, Serialize};

#[derive(Debug, Deserialize, Serialize, Clone)]
pub struct Message {
    pub role: Role,
    pub content: String,
    pub reasoning_content: Option<String>,
    pub prefix: bool,
    tool_call_id: Option<String>,
}
#[derive(Debug, Deserialize, Serialize, Clone)]
pub struct Request {
    pub model: String,
    pub reasoning_effort: ReasoningEffort,
    pub thinking: Option<Thinking>,
    pub messages: Vec<Message>,
    pub max_tokens: Option<u32>,
    pub stream: bool,
}
#[derive(Debug, Deserialize, Serialize, Clone)]
pub struct Thinking {
    pub r#type: String,
}
#[derive(Debug, Deserialize, Serialize, Clone)]
pub struct ChatStreamResponse {
    /// A unique identifier for the chat completion. Each chunk has the same ID.
    pub id: String,
    pub choices: Vec<ChatChoiceStream>,
    /// The Unix timestamp (in seconds) of when the chat completion was created. Each chunk has the same timestamp.
    pub created: u32,
    /// The model to generate the completion.
    pub model: String,

    pub system_fingerprint: Option<String>,
    /// The object type, which is always `chat.completion.chunk`.
    pub object: String,
}

#[derive(Debug, Deserialize, Serialize, Clone, PartialEq)]
pub struct ChatChoiceStream {
    /// The index of the choice in the list of choices.
    pub index: u32,
    pub delta: StreamResponseDelta,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub finish_reason: Option<FinishReason>,
    /// Log probability information for the choice.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub logprobs: Option<ChatChoiceLogprobs>,
}

#[derive(Debug, Deserialize, Serialize, Clone, PartialEq)]
pub struct StreamResponseDelta {
    /// The contents of the chunk message.
    pub content: Option<String>,
    /// The role of the author of this message.
    pub role: Option<Role>,
    /// The refusal message generated by the model.
    pub reasoning_content: Option<String>,
}

impl From<kernel::message::RoleMessage> for Message {
    fn from(value: kernel::message::RoleMessage) -> Self {
        let role = value.role();
        let (content, _paths) = value.clone().to_tuple();
        match value {
            kernel::message::RoleMessage::Assistant(informations, prefix) => {
                let origin = content;
                let mut reasoning_content = vec![];
                let mut content = vec![];
                let mut has_tool_call = false;
                for info in informations {
                    if let Information::Function(tag, full) = &info {
                        if tag == "think" {
                            reasoning_content.push(info);
                            continue;
                        }
                        if tag == "tool_call" {
                            has_tool_call = true;
                        }
                    }
                    content.push(info);
                }
                if has_tool_call {
                    return Message {
                        role: role,
                        content: origin,
                        prefix: prefix,
                        reasoning_content: None,
                        tool_call_id: None,
                    };
                }
                let (reasoning_content, _) = Information::join(reasoning_content);
                let (content, _) = Information::join(content);
                return Message {
                    role: role,
                    reasoning_content: Some(reasoning_content),
                    content: content,
                    prefix: prefix,
                    tool_call_id: None,
                };
            }
            kernel::message::RoleMessage::Tool(tool_call_id, _informations) => {
                return Message {
                    role: Role::User,
                    content: content,
                    reasoning_content: None,
                    prefix: false,
                    tool_call_id: None,
                };
            }
            _ => Message {
                role: role,
                content: content,
                reasoning_content: None,
                prefix: false,
                tool_call_id: None,
            },
        }
    }
}

pub struct DeepseekClient {
    pub model: String,
    pub client: Client<OpenAIConfig>,
}
#[async_trait]
impl ChatClient for DeepseekClient {
    fn model_info(&self) -> (ModelFamily, String) {
        (ModelFamily::DeepSeek, self.model.to_string())
    }
    async fn stream(
        &self,
        messages: Vec<kernel::message::RoleMessage>,
    ) -> anyhow::Result<ChunkStream> {
        let messages = messages.into_iter().map(|v| v.into()).collect();
        let request = Request {
            model: self.model.clone(),
            reasoning_effort: ReasoningEffort::Low,
            thinking: Some(Thinking {
                r#type: "enabled".to_string(),
            }),
            messages: messages,
            max_tokens: None,
            stream: true,
        };
        let stream = self
            .client
            .chat()
            .create_stream_byot::<Request, ChatStreamResponse>(request)
            .await?;
        let mut in_think = false;
        let stream = stream.map(move |r| {
            let r = r
                .map(|mut v| {
                    let text = v.choices[0].delta.content.take();
                    let reasoning = v.choices[0].delta.reasoning_content.take();
                    if let Some(reasoning) = reasoning {
                        if !in_think {
                            in_think = true;
                            return format!("<think>\n{}", reasoning);
                        } else {
                            return reasoning;
                        }
                    }
                    if let Some(text) = text {
                        if in_think {
                            in_think = false;
                            return format!("\n</think>\n{}", text);
                        } else {
                            return text;
                        }
                    }
                    return "".to_string();
                    // println!("{}", v);
                    // "".to_string()
                })
                .map(|v| Ok(v))
                .flatten()
                .map_err(|e| anyhow::anyhow!(e));
            r
        });
        return Ok(stream.boxed());
    }
}
